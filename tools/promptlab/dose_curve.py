#!/usr/bin/env python3
"""Controlled dose pairs from prompt-lab results (P2.21 review DES-2).

    python tools/promptlab/dose_curve.py results/*.json --out reports/<name>.md

A dose effect can only be read from the **same** scripted population: two
different sets (a stage set vs the probe set) differ in stage, path mix and
prompt, so a difference between them is a set effect, not a dose effect. This
tool groups every results document by exercise, keeps only groups that ran the
identical case-id set, and pairs them by dose.

Per pair it prints the run-level percentages (informational: two draws of one
prompt are not independent) and a per-prompt table with one draw per prompt and
a two-sided Fisher exact p, which is the honest test at this n.
"""
import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import lab  # noqa: F401  (score imports lab; keeps the path contract identical)
from score import annotate, pair_counts


def group(doc_path):
    """(exercise, dose, stages, case ids, rows) for every exercise in one document."""
    doc = json.loads(Path(doc_path).read_text(encoding="utf-8"))
    rows = annotate(doc)
    groups = {}
    for r in rows:
        ex = r.get("exercise")
        if not ex:
            continue
        g = groups.setdefault(ex, {"exercise": ex, "dose": r.get("dose"),
                                   "stages": set(), "ids": set(), "rows": []})
        g["rows"].append(r)
        g["ids"].add(r["id"])
        g["stages"].add(r["stage"])
    return groups, rows


def _stage_label(stages):
    return "/".join(str(s) for s in sorted(stages)) if stages else "?"


def _pair(a, b, metric):
    ha, na, hb, nb, p = pair_counts(a["rows"], b["rows"], metric)
    return ha, na, hb, nb, p


def _fmt_p(p):
    if p is None:
        return "—"
    return "< 0.001" if p < 0.001 else "%.3f" % p


def build(docs, run=1):
    groups = []
    by_ids = {}
    for path in docs:
        gs, _rows = group(path)
        for ex in sorted(gs):
            g = gs[ex]
            g["file"] = Path(path).name
            groups.append(g)
            by_ids.setdefault(frozenset(g["ids"]), []).append(g)
    lines = []
    A = lines.append
    A("# Controlled dose pairs — same scripted population")
    A("")
    A("Generated by `tools/promptlab/dose_curve.py` from: "
      + ", ".join("`%s`" % Path(d).name for d in docs) + ".")
    A("")
    A("A pair is listed only when both exercises ran the **identical case-id set** — same "
      "prompts, same stage, same path mix — so the only thing that changed is the steering "
      "dose. Two different sets cannot measure a dose effect (review DES-2).")
    A("")
    A("Percentages count every prompt twice (two draws); the per-prompt columns use one draw "
      "per prompt and a two-sided Fisher exact p.")
    A("")
    A("| population | stage | exercise | dose | cases | read | first-beat |")
    A("|---|---|---|---|---|---|---|")
    for g in sorted(groups, key=lambda g: (_stage_label(g["stages"]), g["exercise"])):
        read = [r for r in g["rows"] if r.get("valid") and not r.get("schema_warnings")]
        rh = sum(bool(r.get("read_ok_hit")) for r in read)
        fh = sum(bool(r.get("first_fit")) for r in read)
        A(f"| {g['file']}:{g['exercise']} | {_stage_label(g['stages'])} | {g['exercise']} | "
          f"{g['dose'] if g['dose'] is not None else '—'} | {len(g['ids'])} | "
          f"{(rh / len(read) if read else 0):.1%} | {(fh / len(read) if read else 0):.1%} |")
    A("")
    A("## Same-population pairs")
    A("")
    A("| population | doses | read per prompt | read p | first-beat per prompt | fit p |")
    A("|---|---|---|---|---|---|")
    pairs = 0
    for ids, gs in by_ids.items():
        if len(gs) < 2:
            continue
        gs = sorted(gs, key=lambda g: (g["dose"] if g["dose"] is not None else -1))
        for i in range(len(gs)):
            for j in range(i + 1, len(gs)):
                a, b = gs[i], gs[j]
                if a["dose"] == b["dose"]:
                    continue
                ra, rna, rb, rnb, rp = _pair(a, b, "read_ok_hit")
                fa, fna, fb, fnb, fp = _pair(a, b, "first_fit")
                pairs += 1
                A(f"| {a['exercise']} | {a['dose']} → {b['dose']} | {ra}/{rna} → {rb}/{rnb} | "
                  f"{_fmt_p(rp)} | {fa}/{fna} → {fb}/{fnb} | {_fmt_p(fp)} |")
    A("")
    if not pairs:
        A("_No same-population pair in these documents._")
    A("")
    return "\n".join(lines)


def main():
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("results", nargs="+", help="results JSON files")
    p.add_argument("--out", default=None, help="write Markdown here (default stdout)")
    p.add_argument("--run", type=int, default=1,
                   help="which draw represents a prompt in the per-prompt test (default 1)")
    a = p.parse_args()
    md = build(a.results, a.run)
    if a.out:
        out = Path(a.out)
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(md + "\n", encoding="utf-8")
        print(f"wrote {out}")
    else:
        print(md)
    return 0


if __name__ == "__main__":
    sys.exit(main())
